function [f, g, h] = EngProb5_Truss200(x)
if nargin == 0
    f = struct('n', 29, 'ng', 200, 'nh', 0, 'lb', 0.1*ones(1,29), 'ub', 20*ones(1,29));
    g = []; h = [];
    return
end
ps = size(x,1);
f = zeros(ps,1); g = zeros(ps,200); h = zeros(ps,0);
for i = 1:ps
    [f(i,1), g(i,:)] = Truss200_Stress(x(i,:));
end
end

function [Weight, g] = Truss200_Stress(x)
persistent D
if isempty(D)
    [D.coordx, D.coordy, D.member, D.c1, D.c2] = Truss200_Data();
    D.member = double(D.member);
    D.n1 = D.member(:,1);
    D.n2 = D.member(:,2);
    D.dx = D.coordx(D.n2) - D.coordx(D.n1);
    D.dx = D.dx(:);
    D.dy = D.coordy(D.n2) - D.coordy(D.n1);
    D.dy = D.dy(:);
    D.len = sqrt(D.dx.^2 + D.dy.^2);
    D.len = D.len(:);
    D.cos = D.dx ./ D.len;
    D.cos = D.cos(:);
    D.sin = D.dy ./ D.len;
    D.sin = D.sin(:);
    D.fixed = [2*76-1, 2*76, 2*77-1, 2*77];
end
x = x(:).';               % 1x29
area = distribute_areas_200(x);
Weight = 0.283 * sum(area(:) .* D.len(:));
K = assemble_K_200(area, D);
loads = get_loads_200(D.c1, D.c2);
g = zeros(1, 200);
for c = 1:3
    F = zeros(154, 1);
    nds = loads{c}.nodes;
    F(2*nds-1) = loads{c}.fx;
    F(2*nds)   = loads{c}.fy;
    Kc = K;
    Fc = F;
    Kc(D.fixed, :) = 0;
    Kc(:, D.fixed) = 0;
    Kc(D.fixed, D.fixed) = eye(4);
    Fc(D.fixed) = 0;
    U = Kc \ Fc;
    du = U(2*D.n2-1) - U(2*D.n1-1);
    dv = U(2*D.n2)   - U(2*D.n1);
    sigma = 30000 * (du .* D.cos + dv .* D.sin) ./ D.len;
    viol = max(0, sigma - 10) + max(0, -10 - sigma);
    g = max(g, viol');
end
end
