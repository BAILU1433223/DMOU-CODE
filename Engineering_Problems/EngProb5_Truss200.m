function K = assemble_K_200(area, D)
E = 30000;
K = zeros(154, 154);
for e = 1:200
    cx = D.cos(e);
    cy = D.sin(e);
    L  = D.len(e);
    k  = area(e) * E / L;
    ke = k * [cx*cx, cx*cy, -cx*cx, -cx*cy;
              cx*cy, cy*cy, -cx*cy, -cy*cy;
              -cx*cx, -cx*cy, cx*cx, cx*cy;
              -cx*cy, -cy*cy, cx*cy, cy*cy];
    dofs = [2*D.n1(e)-1, 2*D.n1(e), 2*D.n2(e)-1, 2*D.n2(e)];
    K(dofs, dofs) = K(dofs, dofs) + ke;
end
end
function loads = get_loads_200(c1, c2)
loads = cell(3, 1);
loads{1}.nodes = c1(:);
loads{1}.fx = ones(size(c1(:)));
loads{1}.fy = zeros(size(c1(:)));
loads{2}.nodes = c2(:);
loads{2}.fx = zeros(size(c2(:)));
loads{2}.fy = -10 * ones(size(c2(:)));
all_nodes = (1:77)';
loads{3}.nodes = all_nodes;
loads{3}.fx = double(ismember(all_nodes, c1));
loads{3}.fy = -10 * double(ismember(all_nodes, c2));
end

